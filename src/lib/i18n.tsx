export type TranslationKey = keyof typeof translations.ar;

interface LanguageContextType {
  lang: "ar" | "fr";
  setLang: (l: "ar" | "fr") => void;
  t: (key: TranslationKey) => string;
  dir: "rtl" | "ltr";
}

const LanguageContext = createContext<LanguageContextType>(null!);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<"ar" | "fr">("ar");

  useEffect(() => {
    const stored = localStorage.getItem("transport:locale");
    if (stored === "ar" || stored === "fr") {
      setLangState(stored);
      document.documentElement.lang = stored;
      document.documentElement.dir = stored === "fr" ? "ltr" : "rtl";
    }
  }, []);

  const setLang = (l: "ar" | "fr") => {
    setLangState(l);
    localStorage.setItem("transport:locale", l);
    document.documentElement.lang = l;
    document.documentElement.dir = l === "fr" ? "ltr" : "rtl";
  };

  const t = (key: TranslationKey): string => {
    return translations[lang]?.[key] || translations.ar[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, dir: lang === "fr" ? "ltr" : "rtl" }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
